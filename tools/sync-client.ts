/**
 * shared/core → Cocos 客户端单向同步：拷贝源码到 client/assets/scripts/generated/，
 * 把包导入改写为相对路径。客户端内不得手改生成物；--check 校验一致（CI 门禁）。
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'client/assets/scripts/generated');
const HEADER = '// AUTO-GENERATED by tools/sync-client.ts — do not edit. Source: ';

const SOURCES = [
  { from: 'packages/shared/src', to: 'shared', skip: new Set(['schema.ts']) },
  { from: 'packages/core/src', to: 'core', skip: new Set<string>() },
];

export function buildOutputs(): Map<string, string> {
  const files = new Map<string, string>();
  for (const s of SOURCES) {
    for (const name of readdirSync(join(ROOT, s.from)).sort()) {
      if (!name.endsWith('.ts') || s.skip.has(name)) continue;
      const src = readFileSync(join(ROOT, s.from, name), 'utf8').replace(/from '@jinli\/shared'/g, "from '../shared'");
      files.set(join(s.to, name), `${HEADER}${s.from}/${name}\n${src}`);
    }
  }
  return files;
}

function listExisting(dir: string, base = dir, acc: string[] = []): string[] {
  if (!existsSync(dir)) return acc;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) listExisting(full, base, acc);
    else if (e.name.endsWith('.ts')) acc.push(full.slice(base.length + 1));
  }
  return acc;
}

function main(): void {
  const check = process.argv.includes('--check');
  const jsonOut = process.argv.find((a) => a.startsWith('--json='))?.slice(7);
  const outputs = buildOutputs();
  const problems: string[] = [];
  for (const [rel, content] of outputs) {
    const target = join(OUT, rel);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === content) continue;
    if (check) problems.push(`${current === null ? 'missing' : 'stale'}: ${rel}`);
    else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  for (const rel of listExisting(OUT)) {
    if (outputs.has(rel)) continue;
    if (check) problems.push(`orphan: ${rel}`);
    else rmSync(join(OUT, rel));
  }
  if (jsonOut) {
    mkdirSync(dirname(resolve(jsonOut)), { recursive: true });
    writeFileSync(resolve(jsonOut), JSON.stringify({ ok: problems.length === 0, files: outputs.size, problems }, null, 2));
  }
  if (check && problems.length) {
    console.error(`client sync check failed (run npm run sync-client):\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log(check ? `client sync check: ${outputs.size} files in sync` : `client sync: ${outputs.size} files written`);
}

main();
